/**
 * Link photos to places.
 *   1) Put files in public/places/ named after the place id:  HK001.jpg, BD002.webp, …  (jpg, jpeg, png, webp)
 *   2) npm run images
 * It writes src/data/images.ts and reports places that still have no photo, plus files that match no place.
 */
import { readdirSync, writeFileSync, existsSync, statSync } from 'node:fs'
import { PLACES } from '../src/data/places'

const DIR = 'public/places'
const files = existsSync(DIR) ? readdirSync(DIR).filter(f => /\.(jpe?g|png|webp)$/i.test(f)) : []
const ids = new Set(PLACES.map(p => p.id))
const map: Record<string, string> = {}
const unknown: string[] = []
const heavy: string[] = []
for (const f of files) {
  const id = f.replace(/\.[^.]+$/, '')
  if (!ids.has(id)) { unknown.push(f); continue }
  map[id] = `places/${f}`
  if (statSync(`${DIR}/${f}`).size > 400_000) heavy.push(f)
}
writeFileSync('src/data/images.ts',
  `// Generated by \`npm run images\` from the files in public/places/ (named <place id>.jpg|jpeg|png|webp). Do not edit by hand.\n` +
  `export const LOCAL_IMAGES: Record<string, string> = ${JSON.stringify(map, null, 2)}\n`)
const missing = PLACES.filter(p => !map[p.id])
console.log(`${Object.keys(map).length}/${PLACES.length} places have a photo.`)
if (unknown.length) console.log(`Files that match no place id (ignored): ${unknown.join(', ')}`)
if (heavy.length) console.log(`Larger than 400 KB (slow on phones — consider resizing to ~1000px wide): ${heavy.join(', ')}`)
if (missing.length) console.log(`Still without a photo (${missing.length}): ${missing.map(p => p.id).join(' ')}`)
