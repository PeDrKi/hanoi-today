// Shared by scripts/dump-dataset.ts and scripts/import-places.ts: renders src/data/dataset.ts.
import type { RawPlace, MenuEntry } from '../../src/types'
import type { SeasonInfo } from '../../src/data/seasons'
import type { LocalInfo } from '../../src/data/localMode'
import type { Opening } from '../../src/data/schedule'

export interface Dataset {
  places: RawPlace[]
  seasons: Record<string, SeasonInfo>
  local: Record<string, LocalInfo>
  schedule: Record<string, Opening>
  strenuous: string[]
  menus: Record<string, MenuEntry>
}

const line = (v: unknown) => JSON.stringify(v)
const rec = (name: string, type: string, o: Record<string, unknown>) =>
  `export const ${name}: Record<string, ${type}> = {\n` + Object.entries(o).map(([k, v]) => `  ${line(k)}: ${line(v)},`).join('\n') + '\n}\n'

export function renderDataset(d: Dataset): string {
  return `// GENERATED by \`npm run import:places\` (from the Excel template) or \`npm run dump:dataset\` — edit the spreadsheet, not this file.
// Every table here is keyed by place id. Nothing in this file is invented: empty cells stay empty.
import type { RawPlace, MenuEntry } from '../types'
import type { SeasonInfo } from './seasons'
import type { LocalInfo } from './localMode'
import type { Opening } from './schedule'

export const RAW_PLACES: RawPlace[] = [
${d.places.map(p => '  ' + line(p) + ',').join('\n')}
]

${rec('SEASONS', 'SeasonInfo', d.seasons)}
${rec('LOCAL', 'LocalInfo', d.local)}
${rec('SCHEDULE_DATA', 'Opening', d.schedule)}
export const STRENUOUS: string[] = ${line(d.strenuous)}

${rec('MENUS_DATA', 'MenuEntry', d.menus)}`
}
